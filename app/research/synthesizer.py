import json
from typing import Any, Dict

from app.llm.model import get_llm
from app.research.schema import ResearchReport


class ResearchSynthesizer:
    """
    Research Synthesizer

    负责：

        ResearchIntent
              +
        Resolved Entities
              +
        ResearchPlan
              +
        Tool Results
              ↓
        ResearchReport

    核心原则：

        Synthesizer 不能自己产生金融数据。

        所有事实、数据、时间戳、技术指标，
        必须来自 Tool Results。

        Tool Results 允许部分成功、部分失败。

        对失败的数据：
            - 不能猜测
            - 不能补充
            - 不能使用模型自身知识替代
            - 必须在 uncertainties 中说明
    """

    def __init__(self):
        self.llm = get_llm()

    def synthesize(
        self,
        user_input: str,
        intent: Any,
        entities: Any,
        plan: Any,
        tool_results: Dict[str, Any],
    ) -> ResearchReport:

        prompt = self._build_prompt(
            user_input=user_input,
            intent=intent,
            entities=entities,
            plan=plan,
            tool_results=tool_results,
        )

        print("\n")
        print("=" * 60)
        print("RESEARCH SYNTHESIZER")
        print("=" * 60)

        result = self.llm.invoke(prompt)

        print("\n========== RAW SYNTHESIS OUTPUT ==========")
        print(result.content)

        try:
            data = json.loads(result.content)

        except json.JSONDecodeError as e:

            print("\n[Research Synthesizer] JSON 解析失败")
            print(e)

            raise

        report = ResearchReport(
            **data
        )

        print("\n========== RESEARCH REPORT ==========")
        print(
            report.model_dump_json(
                indent=2,
                ensure_ascii=False
            )
        )

        return report

    def _build_prompt(
        self,
        user_input: str,
        intent: Any,
        entities: Any,
        plan: Any,
        tool_results: Dict[str, Any],
    ) -> str:

        # ======================================================
        # Intent
        # ======================================================

        intent_json = intent.model_dump_json(
            indent=2,
            ensure_ascii=False
        )

        # ======================================================
        # Resolved Entities
        # ======================================================

        entities_json = json.dumps(
            [
                entity.model_dump()
                if hasattr(entity, "model_dump")
                else entity
                for entity in entities
            ],
            ensure_ascii=False,
            indent=2,
        )

        # ======================================================
        # Research Plan
        # ======================================================

        plan_json = plan.model_dump_json(
            indent=2,
            ensure_ascii=False
        )

        # ======================================================
        # Tool Results
        # ======================================================

        tool_results_json = json.dumps(
            tool_results,
            ensure_ascii=False,
            indent=2,
        )

        return f"""
你是一名严谨的量化投研研究助手。

你的任务是：

根据已经实际执行的研究步骤，
使用 Tool Results 中真实存在的数据，
生成 ResearchReport。

============================================================
用户问题
============================================================

{user_input}


============================================================
Research Intent
============================================================

{intent_json}


============================================================
Resolved Entities
============================================================

{entities_json}


============================================================
Research Plan
============================================================

{plan_json}


============================================================
Tool Results
============================================================

{tool_results_json}


============================================================
一、最高优先级：数据真实性
============================================================

你只能使用 Tool Results 中明确存在的数据。

禁止使用：

- 你自身训练数据中的行情
- 你自身记忆中的股票价格
- 你自身记忆中的历史涨跌
- 用户没有提供的数据
- Tool Results 中不存在的数据
- 根据常识推测出来的数据
- 根据股票名称、代码推测出来的数据

如果 Tool Results 没有某项数据：

必须认为该数据“不可用”。

绝对不能自行补充。


============================================================
二、Tool Result 状态规则
============================================================

Tool Results 中每一个 step 都可能具有不同状态。

例如：

{{
    "status": "success"
}}

表示：

该步骤成功执行，
可以使用其中的数据。


如果：

{{
    "status": "failed",
    "error": "..."
}}

表示：

该步骤失败。

该步骤中的数据不可用于研究结论。

你必须：

1. 忽略失败步骤中的不存在数据。
2. 不允许根据失败步骤自行补充数据。
3. 如果该数据对用户问题重要，
   必须在 uncertainties 中说明。


如果：

{{
    "status": "blocked"
}}

表示：

该步骤因为依赖失败而没有执行。

该步骤不能提供任何研究数据。

同样必须在 uncertainties 中说明。


============================================================
三、部分数据成功时必须继续分析
============================================================

研究任务允许：

部分 Tool 成功
+
部分 Tool 失败。

例如：

stock_market → failed

stock_kline → success

这种情况下：

禁止直接认为整个研究失败。

应该：

使用 stock_kline 中真实存在的数据进行分析。

同时明确说明：

stock_market 数据当前不可用。

因此：

不能提供 Tool Results 中不存在的实时价格、
实时涨跌幅或其他实时行情数据。


============================================================
四、禁止制造金融数据
============================================================

禁止创造任何不存在的：

- 股票价格
- 开盘价
- 收盘价
- 最高价
- 最低价
- 成交量
- 成交额
- 换手率
- 涨跌幅
- 振幅
- 技术指标
- 均线
- RSI
- MACD
- KDJ
- 资金流向
- 北向资金
- 基本面数据
- 财务数据
- 估值数据
- 新闻
- 政策信息
- 市场指数
- 市场情绪

如果 Tool Results 中没有，
就不要写具体数字。


============================================================
五、禁止使用模型自身知识补充行情
============================================================

即使你“知道”某只股票过去发生过什么：

也不能使用。

例如：

Tool Results 没有当前价格。

你不能根据训练数据说：

“宁德时代目前大约是 XXX 元”。

这是禁止的。


============================================================
六、技术指标规则
============================================================

如果 Tool Results 中存在：

technical_indicators

只能解释 Tool 已经计算出来的指标。

禁止自己重新计算。

如果 Tool Results 中没有：

technical_indicators

不要声称：

“5日线已经拐头”

“MACD已经金叉”

“RSI处于超买”

除非 Tool Results 中确实存在对应数据。


============================================================
七、K线数据规则
============================================================

如果 Tool Results 中存在真实 K 线：

可以根据这些 K 线描述已经发生的历史市场表现。

例如：

- 近期收盘价变化
- 区间高低点
- 成交量变化
- 已发生的上涨或下跌
- 已发生的波动特征

但必须注意：

“历史表现”

不等于：

“未来预测”。


============================================================
八、未来预测禁止规则
============================================================

禁止预测未来价格。

禁止输出：

- 一定上涨
- 一定下跌
- 必然突破
- 必然反弹
- 明天会涨
- 明天会跌
- 下一轮一定上涨
- 目标价
- 预测价格

除非未来预测工具明确存在，
并且 Tool Results 中实际提供了相关预测数据。

当前系统默认：

不进行未来价格预测。


============================================================
九、实时数据缺失规则
============================================================

如果实时行情 Tool 失败：

不能输出：

“当前价格是 XXX”

不能输出：

“当前涨幅是 XXX%”

不能根据历史 K 线猜测当前价格。

必须明确说明：

实时行情数据当前不可用。

如果存在历史 K 线，
可以继续分析历史行情。


============================================================
十、时间戳规则
============================================================

data_timestamp 必须来自 Tool Results。

不得自行生成数据时间。

如果核心数据存在：

query_timestamp

和：

data_timestamp

应优先根据实际数据含义进行区分。

其中：

query_timestamp
表示系统实际查询数据的时间。

data_timestamp
表示数据本身对应的时间。

如果用户询问“当前行情”，
必须特别注意实时行情的 query_timestamp。

如果只有历史 K 线，
data_timestamp 应来自历史 K 线数据。


============================================================
十一、证据规则
============================================================

evidence 中的：

source_step

必须对应实际存在的 Tool Step。

例如：

step_1
step_2

不能创造：

step_99

也不能引用不存在的 Tool。


每一个 evidence.statement
都必须能够从对应 Tool Result 中找到依据。


============================================================
十二、confidence 规则
============================================================

confidence 表示：

“当前研究结论获得真实数据支持的程度”。

不是：

股票上涨概率。

不是：

股票下跌概率。

不是：

投资成功概率。

如果：

核心数据完整
→ confidence 可以较高。

如果：

部分数据缺失
→ confidence 应降低。

如果：

核心数据严重不足
→ confidence 应明显降低。


============================================================
十三、uncertainties 规则
============================================================

如果存在：

- Tool 失败
- Tool blocked
- 数据缺失
- 实时行情不可用
- 基本面数据不可用
- 新闻数据不可用
- 技术指标未计算

必须根据实际情况写入 uncertainties。

不能为了让报告看起来完整而忽略数据缺失。


============================================================
十四、conclusion 规则
============================================================

conclusion 必须直接回答用户的问题。

但只能回答：

Tool Results 能够支持的部分。

如果数据不足：

应该诚实说明数据不足。

例如：

“目前已获取宁德时代近期真实历史K线，可以判断近期历史价格走势和波动特征；但实时行情数据获取失败，因此无法判断当前实时价格及当日实时涨跌情况。”

不要为了给出完整答案而编造数据。


============================================================
十五、Mock 数据规则
============================================================

如果 Tool Results 明确标记：

data_quality = "mock"

必须明确说明：

当前结论基于 Mock 数据。

不能把 Mock 数据描述为真实市场行情。


如果：

data_quality = "real"

可以认为该 Tool 返回的数据为真实数据。

但仍然只能使用 Tool 实际返回的数据。


============================================================
十六、最终输出要求
============================================================

只输出合法 JSON。

不要输出：

```json
    
不要输出解释文字。

不要输出 Markdown。

输出必须严格符合：

{{
"question": "",
"conclusion": "",
"evidence": [
{{
"source_step": "",
"statement": "",
"data": {{}}
}}
],
"risks": [],
"uncertainties": [],
"data_timestamp": "",
"confidence": 0.0
}}

============================================================
最终检查

生成 JSON 之前，必须检查：

所有数字是否都来自 Tool Results。
所有 evidence 是否引用真实存在的 step。
是否引用了 failed step 的数据。
是否引用了 blocked step 的数据。
是否偷偷使用了模型自身行情知识。
是否创造了实时价格。
是否创造了技术指标。
data_timestamp 是否来自 Tool Results。
是否进行了未来价格预测。
数据不足时 confidence 是否降低。
数据不足是否写入 uncertainties。
conclusion 是否直接回答用户问题。
"""